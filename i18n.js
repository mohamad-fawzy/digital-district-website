const I18N_KEY = 'dd-lang';

function applyLanguage(lang) {
  const dict = translations[lang] || translations.ar;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!dict[key]) return;
    if (el.hasAttribute('data-i18n-attr')) {
      const attr = el.getAttribute('data-i18n-attr');
      el.setAttribute(attr, dict[key]);
    } else {
      el.textContent = dict[key];
    }
  });

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.title = dict['meta.title'];

  document.querySelectorAll('[data-lang-opt]').forEach(el => {
    el.classList.toggle('active', el.getAttribute('data-lang-opt') === lang);
  });

  localStorage.setItem(I18N_KEY, lang);
}

function initLanguage() {
  const saved = localStorage.getItem(I18N_KEY);
  const lang = saved === 'en' ? 'en' : 'ar';
  applyLanguage(lang);

  const toggle = () => {
    const current = document.documentElement.lang === 'en' ? 'en' : 'ar';
    applyLanguage(current === 'ar' ? 'en' : 'ar');
  };

  document.getElementById('langSwitch')?.addEventListener('click', toggle);
  document.getElementById('langSwitchMobile')?.addEventListener('click', toggle);
}

document.addEventListener('DOMContentLoaded', initLanguage);
